def ident(value):
    return {'status':'OBSERVED' if value else 'NOT_OBSERVED','value':value,'candidates':[value] if value else []}

def message(role,value,parent=None,asset=None):
    return {'role':role,'identity':ident(value),'parent_identity':ident(parent),
            'turn_identity':ident(None),'container_identity':ident(None),'positional_key':None,
            'records':[{'scope':'root','attributes':{'data-message-id':value}}] if value else [],
            'images':[{'asset_identity':ident(asset),'response_identity':ident(value),'selected_resource':True,'records':[]}] if asset else [],
            'metadata_truncated':False}

class MetadataPage:
    def __init__(self,snapshots):self.snapshots=snapshots;self.calls=[]
    def evaluate(self,script,args):
        self.calls.append((script,args))
        value=self.snapshots.pop(0)
        if isinstance(value,Exception):raise value
        return copy.deepcopy(value)

